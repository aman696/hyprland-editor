use hyprland_editor_core::{
    lua::{
        config_inspection,
        replay::{Event, Observed},
        scalar_codec::{NativeValue, Outcome, Rejection},
    },
    AUDITED_MAIN, BASELINE,
};
fn event(order: usize, key: &[u8], value: Observed) -> Event {
    Event {
        order,
        document: "root".into(),
        span: 0..1,
        api: "hl.config".into(),
        arguments: vec![Observed::Table(vec![(Observed::Bytes(key.into()), value)])],
        argument_sources: vec![],
    }
}
#[test]
fn registered_inspection_pins_context_acceptance_and_unknown_api_boundaries() {
    for version in [BASELINE, AUDITED_MAIN] {
        let events = vec![
            event(1, b"general.border_size", Observed::Int(30)),
            event(3, b"autogenerated\0alias", Observed::Int(1)),
            event(4, b"general.gaps_out", Observed::Int(5)),
            event(5, b"general.border_size", Observed::Int(4)),
        ];
        let result = config_inspection::inspect(&events, version).unwrap();
        assert_eq!(result.context.version, version);
        assert!(!result.context.runtime_verified);
        assert_eq!(result.context.numeric_locale.as_deref(), Some("C"));
        assert!(
            result
                .context
                .profile
                .unwrap()
                .primitive_conversions_profiled
        );
        assert_eq!(result.batches.len(),3,"Later inert argument observations must not get native models after an unknown API boundary");
        let first = &result.batches[0].candidates[0];
        if version == BASELINE {
            assert!(matches!(
                first.model_value,
                Some(Outcome::Accepted {
                    native: NativeValue::Int(30),
                    ..
                })
            ));
        } else {
            assert!(matches!(
                first.model_value,
                Some(Outcome::Rejected {
                    error: Rejection::OutOfRange
                })
            ));
        }
        let extra = &result.batches[1].candidates[0];
        assert_eq!(extra.lua_key, "autogenerated");
        assert!(extra.raw_keys[0].contains(&0));
        assert!(matches!(
            extra.model_value,
            Some(Outcome::Accepted {
                native: NativeValue::Int(1),
                ..
            })
        ));
        assert!(result.stopped.unwrap().contains("CssGap"));
        assert!(result
            .batches
            .iter()
            .all(|b| !b.native_values_verified && !b.order_within_call_known));
    }
    let events = [
        event(2, b"general.border_size", Observed::Int(1)),
        event(1, b"general.border_size", Observed::Int(2)),
    ];
    let result = config_inspection::inspect(&events, BASELINE).unwrap();
    assert_eq!(result.batches.len(), 1);
    assert!(result.stopped.unwrap().contains("not ordered"));
}
#[test]
fn model_output_limits_preserve_prior_batches_and_do_not_turn_refusal_into_acceptance() {
    let prior = event(0, b"general.border_size", Observed::Int(1));
    let mut large = event(1, b"general.layout", Observed::Bytes(vec![b'x'; 65536]));
    let Observed::Table(rows) = &mut large.arguments[0] else {
        unreachable!()
    };
    // Both native strings are accepted but their full byte evidence exceeds the
    // per-call bound. No typed version of this call is published as successful.
    rows.push((
        Observed::Bytes(b"general.locale".to_vec()),
        Observed::Bytes(vec![b'x'; 65536]),
    ));
    let result = config_inspection::inspect(&[prior, large], AUDITED_MAIN).unwrap();
    assert_eq!(result.batches.len(), 1);
    assert!(result.stopped.unwrap().contains("budget"));
    let result = config_inspection::inspect(&[], BASELINE).unwrap();
    assert!(result.context.profile.is_none());
    assert!(result.batches.is_empty());
    let mut invalid = event(1, b"general.border_size", Observed::Int(1));
    invalid.api = "hl.exec_cmd".into();
    assert!(config_inspection::inspect(&[invalid], BASELINE).is_err());
}
