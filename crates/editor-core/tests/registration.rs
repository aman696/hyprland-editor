use hyprland_editor_core::{
    lua::{
        registration::{self, Role},
        replay::Observed,
        scalar_codec::{Codec, NativeValue, Outcome, Parser, Rejection},
    },
    AUDITED_MAIN, BASELINE,
};
use std::collections::BTreeSet;
#[test]
fn source_registered_models_keep_declared_metadata_separate_from_versioned_lua_acceptance() {
    let mut parser = Parser::new().unwrap();
    for (version, count) in [(BASELINE, 353), (AUDITED_MAIN, 402)] {
        let entries = registration::entries(version, Role::Global).collect::<Vec<_>>();
        assert_eq!(entries.len(), count);
        assert_eq!(
            entries
                .iter()
                .map(|e| &e.lua_key)
                .collect::<BTreeSet<_>>()
                .len(),
            count
        );
        for e in entries {
            if let Some(codec) = &e.codec {
                parser.decode(codec, &Observed::Nil).unwrap();
            } else {
                assert!(matches!(
                    e.kind.as_str(),
                    "Color" | "Gradient" | "CssGap" | "Vec2" | "FontWeight"
                ));
            }
        }
        let border = registration::find(version, Role::Global, "general:border_size").unwrap();
        assert_eq!(border.declared_bounds.as_ref().unwrap().maximum, Some(20.0));
        let result = parser
            .decode(border.codec.as_ref().unwrap(), &Observed::Int(30))
            .unwrap();
        if version == BASELINE {
            assert!(matches!(
                result,
                Outcome::Accepted {
                    native: NativeValue::Int(30),
                    ..
                }
            ));
        } else {
            assert!(matches!(
                result,
                Outcome::Rejected {
                    error: Rejection::OutOfRange
                }
            ));
        }
        let corner = registration::find(version, Role::Global, "general:resize_corner").unwrap();
        assert!(corner
            .declared_names
            .as_ref()
            .unwrap()
            .iter()
            .any(|n| n.name == b"top_left" && n.value == 1));
        let result = parser
            .decode(
                corner.codec.as_ref().unwrap(),
                &Observed::Bytes(b"top_left".to_vec()),
            )
            .unwrap();
        if version == BASELINE {
            assert!(matches!(
                result,
                Outcome::Rejected {
                    error: Rejection::BadType
                }
            ));
        } else {
            assert!(matches!(
                result,
                Outcome::Accepted {
                    native: NativeValue::Int(1),
                    ..
                }
            ));
        }
        let accel = registration::find(version, Role::Global, "input:accel_profile").unwrap();
        let result = parser
            .decode(
                accel.codec.as_ref().unwrap(),
                &Observed::Bytes(b"unknown".to_vec()),
            )
            .unwrap();
        if version == BASELINE {
            assert!(matches!(result, Outcome::Accepted { .. }));
        } else {
            assert!(matches!(
                result,
                Outcome::Rejected {
                    error: Rejection::BadValue
                }
            ));
        }
        assert!(
            matches!(parser.decode(accel.codec.as_ref().unwrap(),&Observed::Bytes(b"adaptive\0suffix".to_vec())).unwrap(),Outcome::Accepted{native:NativeValue::Bytes(ref v),..} if v==b"adaptive")
        );
        assert_eq!(registration::entries(version, Role::Device).count(), 46);
        for key in [
            "eraser_button_mode",
            "eraser_button_override",
            "pressure_range_min",
            "pressure_range_max",
        ] {
            let e = registration::find(version, Role::Device, key).unwrap();
            assert!(e.codec.is_some());
            assert_eq!(
                e.parent_id.as_deref(),
                Some(format!("input:tablettool:{key}").as_str())
            );
        }
        let extra = registration::by_lua_key(version, "autogenerated").unwrap();
        assert_eq!(extra.role, Role::Bootstrap);
        assert_eq!(extra.native_default, Some(NativeValue::Int(0)));
        assert!(matches!(
            extra.codec,
            Some(Codec::Int {
                minimum: None,
                maximum: None,
                names: None
            })
        ));
    }
    assert!(registration::by_lua_key("future", "general.border_size").is_none());
    assert!(registration::find(BASELINE, Role::Global, "arbitrary").is_none());
    assert_eq!(registration::schema_sha256().len(), 64);
}
#[test]
fn literal_string_choices_match_native_callback_observations_without_changing_nul_order() {
    let fixture: serde_json::Value = serde_json::from_str(include_str!(
        "../../../data/scalar-registration-fixtures.json"
    ))
    .unwrap();
    let unhex = |s: &str| {
        (0..s.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
            .collect::<Vec<_>>()
    };
    let mut parser = Parser::new().unwrap();
    let mut checked = 0;
    for snapshot in fixture["snapshots"].as_array().unwrap() {
        let version = if snapshot["version"] == "baseline" {
            BASELINE
        } else {
            AUDITED_MAIN
        };
        for native in snapshot["values"].as_array().unwrap() {
            if native["lua"]["kind"] != "String" {
                continue;
            }
            let Some(cases) = native["lua"]["validator_cases"].as_array() else {
                continue;
            };
            let identifier = String::from_utf8(unhex(native["id_hex"].as_str().unwrap())).unwrap();
            let entry = registration::find(version, Role::Global, &identifier).unwrap();
            for case in cases {
                let bytes = unhex(case[0].as_str().unwrap());
                let prefix = bytes.split(|b| *b == 0).next().unwrap();
                let expected = cases
                    .iter()
                    .find(|r| unhex(r[0].as_str().unwrap()) == prefix)
                    .unwrap()[1]
                    .as_bool()
                    .unwrap();
                let result = parser
                    .decode(entry.codec.as_ref().unwrap(), &Observed::Bytes(bytes))
                    .unwrap();
                assert_eq!(
                    matches!(result, Outcome::Accepted { .. }),
                    expected,
                    "{version} {identifier}: {case}"
                );
                checked += 1;
            }
        }
    }
    assert_eq!(checked, 54); // three active current validators, 18 independent raw inputs each
                             // Old unsupported-name JSON remains an explicit unknown; choices are closed data.
    let legacy: Codec =
        serde_json::from_str(r#"{"kind":"string","validator":"unimplemented"}"#).unwrap();
    assert!(matches!(
        parser
            .decode(&legacy, &Observed::Bytes(b"text".to_vec()))
            .unwrap(),
        Outcome::Unresolved { .. }
    ));
    assert!(serde_json::from_str::<Codec>(
        r#"{"kind":"string","validator":{"choices":[],"code":"execute"}}"#
    )
    .is_err());
}
#[test]
fn forwarded_vector_validators_match_original_factory_callbacks_for_every_registered_vector() {
    let fixture: serde_json::Value = serde_json::from_str(include_str!(
        "../../../data/scalar-registration-fixtures.json"
    ))
    .unwrap();
    let mut parser = Parser::new().unwrap();
    let mut checked = 0;
    for snapshot in fixture["snapshots"].as_array().unwrap() {
        let version = if snapshot["version"] == "baseline" {
            BASELINE
        } else {
            AUDITED_MAIN
        };
        for native in snapshot["values"]
            .as_array()
            .unwrap()
            .iter()
            .filter(|v| v["lua"]["kind"] == "Vec2")
        {
            let hex = native["id_hex"].as_str().unwrap();
            let id = String::from_utf8(
                (0..hex.len())
                    .step_by(2)
                    .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap())
                    .collect(),
            )
            .unwrap();
            let meta = registration::find(version, Role::Global, &id).unwrap();
            assert!(matches!(meta.codec, Some(Codec::Vec2 { .. })));
            if version == BASELINE {
                assert!(matches!(meta.codec, Some(Codec::Vec2 { validator: None })));
                continue;
            }
            for case in native["lua"]["validator_cases"].as_array().unwrap() {
                let input = Observed::Table(
                    (0..2)
                        .map(|i| {
                            (
                                Observed::Int(i + 1),
                                Observed::Float(f64::from(f32::from_bits(
                                    case[i as usize].as_u64().unwrap() as u32,
                                ))),
                            )
                        })
                        .collect(),
                );
                let result = parser.decode(meta.codec.as_ref().unwrap(), &input).unwrap();
                assert_eq!(
                    matches!(result, Outcome::Accepted { .. }),
                    case[2].as_bool().unwrap(),
                    "{id}: {case}"
                );
                checked += 1;
            }
        }
    }
    assert_eq!(checked, 6 * 17);
}
